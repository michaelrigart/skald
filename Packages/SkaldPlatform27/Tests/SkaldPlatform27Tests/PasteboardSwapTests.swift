import AppKit
import Foundation
import Testing
@testable import SkaldPlatform27

private func privatePasteboard() -> NSPasteboard {
    NSPasteboard(name: NSPasteboard.Name("com.michaelrigart.skald.tests.\(UUID().uuidString)"))
}

private func item(_ entries: [(NSPasteboard.PasteboardType, Data)]) -> NSPasteboardItem {
    let item = NSPasteboardItem()
    for (type, data) in entries { item.setData(data, forType: type) }
    return item
}

private func contents(of pasteboard: NSPasteboard) -> [[String: Data]] {
    (pasteboard.pasteboardItems ?? []).map { item in
        Dictionary(uniqueKeysWithValues: item.types.compactMap { type in
            item.data(forType: type).map { (type.rawValue, $0) }
        })
    }
}

private let stagedText = "~skald-ok~"
private let custom = NSPasteboard.PasteboardType("com.example.skald-test")

private func filled() -> NSPasteboard {
    let pasteboard = privatePasteboard()
    pasteboard.clearContents()
    pasteboard.writeObjects([
        item([(.string, Data("first".utf8)), (.rtf, Data("{\\rtf1 first}".utf8)), (custom, Data([0, 1, 2, 255]))]),
        item([(.string, Data("second".utf8)), (.html, Data("<b>second</b>".utf8))]),
        item([(.tiff, Data(repeating: 7, count: 64))]),
    ])
    return pasteboard
}

@MainActor @Test func theSnapshotRestoresEveryItemWithEveryType() {
    let pasteboard = filled()
    defer { pasteboard.releaseGlobally() }
    let before = contents(of: pasteboard)
    #expect(before.count == 3)

    let swap = PasteboardSwap(pasteboard)
    #expect(swap.stage(stagedText) == .staged)
    #expect(contents(of: pasteboard) != before)
    #expect(swap.restore() == .restored)
    #expect(contents(of: pasteboard) == before)
}

@MainActor @Test func theStagedItemCarriesTheStringAndTheThreeClipboardManagerMarkers() throws {
    let pasteboard = filled()
    defer { pasteboard.releaseGlobally() }
    #expect(PasteboardSwap(pasteboard).stage(stagedText) == .staged)

    let items = try #require(pasteboard.pasteboardItems)
    #expect(items.count == 1)
    let staged = try #require(items.first)
    #expect(staged.string(forType: .string) == stagedText)
    for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
        #expect(staged.types.contains(NSPasteboard.PasteboardType(marker)), "missing \(marker)")
    }
}

@MainActor @Test func anEmptyPasteboardIsLeftEmptyAfterTheRestore() {
    let pasteboard = privatePasteboard()
    defer { pasteboard.releaseGlobally() }
    pasteboard.clearContents()
    let swap = PasteboardSwap(pasteboard)
    #expect(swap.stage(stagedText) == .staged)
    #expect(swap.restore() == .restored)
    #expect(contents(of: pasteboard).isEmpty)
}

@MainActor @Test func theRestoreLeavesAlonePasteboardContentSomeoneElseWrote() {
    let pasteboard = filled()
    defer { pasteboard.releaseGlobally() }
    let swap = PasteboardSwap(pasteboard)
    #expect(swap.stage(stagedText) == .staged)

    pasteboard.clearContents()
    pasteboard.setString("written by another app", forType: .string)
    let theirs = contents(of: pasteboard)

    #expect(swap.restore() == .leftAlone)
    #expect(contents(of: pasteboard) == theirs)
}

