import AppKit
import Foundation

@MainActor
final class PasteboardSwap {
    enum Staging: Equatable {
        case staged, changedSinceSnapshot, unrestorable

        var refusal: String? {
            switch self {
            case .staged: nil
            case .changedSinceSnapshot: "the clipboard changed since the snapshot"
            case .unrestorable: "the clipboard holds concealed or promised content"
            }
        }
    }

    enum Restoration: Equatable {
        case restored, leftAlone
    }

    nonisolated static let markerTypes = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
    ].map { NSPasteboard.PasteboardType(rawValue: $0) }

    nonisolated private static let neverReplayedTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
    ]

    private struct Entry {
        let type: NSPasteboard.PasteboardType
        let data: Data?
    }

    private let pasteboard: NSPasteboard
    private let saved: [[Entry]]
    private let snapshotChangeCount: Int
    private var changeCountAfterStage: Int?

    init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        snapshotChangeCount = pasteboard.changeCount
        saved = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.map { Entry(type: $0, data: item.data(forType: $0)) }
        }
    }

    var canRestoreFaithfully: Bool {
        Self.isRestorable(saved.map { $0.map { (type: $0.type.rawValue, hasData: $0.data != nil) } })
    }

    nonisolated static func isRestorable(_ items: [[(type: String, hasData: Bool)]]) -> Bool {
        items.allSatisfy { item in
            item.allSatisfy { $0.hasData && !neverReplayedTypes.contains($0.type) }
        }
    }

    func stage(_ text: String) -> Staging {
        guard canRestoreFaithfully else { return .unrestorable }
        guard pasteboard.changeCount == snapshotChangeCount else { return .changedSinceSnapshot }
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for marker in Self.markerTypes { item.setData(Data(), forType: marker) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        changeCountAfterStage = pasteboard.changeCount
        return .staged
    }

    /// The clipboard still holds what `stage` put there: nobody copied anything since.
    var holdsStage: Bool {
        changeCountAfterStage == pasteboard.changeCount
    }

    /// `holdsStage` as it stands now, for a job that runs off the main actor: it asks the pasteboard by name.
    func stageCheck() -> @Sendable () -> Bool {
        let name = pasteboard.name
        let staged = changeCountAfterStage
        return { staged == NSPasteboard(name: name).changeCount }
    }

    func restore() -> Restoration {
        guard changeCountAfterStage != nil else { return .restored }
        guard holdsStage else { return .leftAlone }
        pasteboard.clearContents()
        let items = saved.filter { !$0.isEmpty }.map { entries in
            let item = NSPasteboardItem()
            for entry in entries {
                if let data = entry.data { item.setData(data, forType: entry.type) }
            }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        return .restored
    }
}
